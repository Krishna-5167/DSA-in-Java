public class else_if {

     public static void main(String args[]){
               int age = 12;

               if(age>=18){
                System.out.println("Adult");
               }
               else if(age>=13 && age<18){
                System.out.println("Teenagers");
               }
               else{
                System.out.println("Not Adult");
               }
               
        }
    
}

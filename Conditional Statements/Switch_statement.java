public class Switch_statement {

    public static void main(String args[]){
               int number = 2;

               switch(number){
                case 1 : System.out.println("samosa");
                                break;
                case 2 : System.out.println("mango shake");
                                break;
                case 3 : System.out.println("juice");
                                break;
                default : System.out.println("wake up");
               }
               
        }
    
}
